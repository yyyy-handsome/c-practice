#include <stdio.h>

/* 第 12 题（教材 108 页）

   一根 393cm 的长杆，截成 81cm、41cm、29cm 三种短杆，
   要求 81cm 和 41cm 各至少截一根，求余料最短的方案。

   思路：穷举。
   三种根数的组合总量不大，全部试一遍，
   边试边记录"余料最小"的那一组即可。
   这类"求最优方案"的题，优先想穷举。 */

int main(void)
{
    int a, b, c;                 /* 81cm、41cm、29cm 各截几根 */
    int used, left;              /* 用掉的总长度、剩下的余料 */
    int best = 394;              /* 当前最小余料，初值比任何可能值都大(无论何种结果394都是最大的余料)  用394是为了避免393=393的特殊情况*/
    int ba = 0, bb = 0, bc = 0;  /* 记住最优方案对应的三根数 */

    for (a = 1; 81 * a <= 393; a++) {         /* 81cm 至少 1 根 */
        for (b = 1; 41 * b <= 393; b++) {     /* 41cm 至少 1 根 */
            for (c = 0; 29 * c <= 393; c++) { /* 29cm 可以 0 根 */
                used = 81 * a + 41 * b + 29 * c;

                if (used > 393) continue;     /* 超过杆长，这组不成立 所以后面的都是小于393的*/

                left = 393 - used;            /*表示找每一组循环方案所剩余的余料！！(会有很多组 但在循环里会一直交换值)*/
                if (left < best) {            /* 找到更短的余料 */
                    best = left;
                    ba = a; bb = b; bc = c;   /* 顺便记下这组方案 */
                }
            }
        }
    }

    printf("leftover = %d cm\n", best);
    printf("81cm x %d, 41cm x %d, 29cm x %d\n", ba, bb, bc);
    return 0;
}