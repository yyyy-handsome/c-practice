#include <stdio.h>

int main(){
    int i,j,n;
    int a[1000];                    /* 最多放 1000 天记录，下标 0 ~ 999 */

    scanf("%d", &n);                //先输入一个值给n
    for (i = 0; i < n; i++){       //知道n值后就i知道输入多少个数组的值
        scanf("%d",&a[i]);          /* 第 i 天的记录存进 a[i]，i 从 0 开始 */
    }

    /* ================= 第一问：一共几天 ================= */
    int signDays = 0;               /* signdays表示签到的天数   计数器必须写在循环外面；写在里面会每圈被清零 */
    for (j = 0; j < n; j++){
        if (a[j] == 1) signDays++;  /* 是 1 就加一。注意是 == 比较，写成 = 会变成赋值，永远为真 */
    }
    printf("signDays=%d\n",signDays);  /* 格式要和题目一字不差，等号两边不能加空格 */

    /* ================= 第二问：最长连续 =================
       cur  当前这一段连了几天，断了就归零
       best 到目前为止最长的一段，只增不减
       好比打球：cur 是"现在这波连得几分"，best 是"全场最高连击" */
    int cur = 0,best = 0;           /* best 从 0 开始：全是 0 时正好输出 0 */            //cur表示连续签到几天   best表示最高连续几天签到
    for (j = 0; j < n; j++){
        if (a[j] == 1) cur++;       /* 签到：当前连击加一 */
        if (cur > best) best = cur; /* 加完立刻比较，这样"连续到结尾"的情况也不会漏 */
        if (a[j] == 0) cur = 0;     /* 断了：cur 归零；best 不动，它只记最高 */
    }
    printf("maxStreak=%d\n",best);  /* 只输出 best；cur 是过程变量，打印它会判错 */
    return 0;
}
