#include <stdio.h>

/* 第 15 题（教材 108 页）

   四位数车牌，满足三个条件：
     1. 前两位数字相同
     2. 后两位数字相同
     3. 整个四位数是一个整数的平方

   思路：不要从 1000 试到 9999，而是直接"造"出来。
   设前两位都是 a，后两位都是 b：
       千位 a、百位 a、十位 b、个位 b
       = 1000a + 100a + 10b + b
       = 1100a + 11b
   这样只需枚举 a(1~9) 和 b(0~9)，一共 90 种组合。 */

int main(void)
{
    int a, b;        /* a: 前两位的数字，b: 后两位的数字 */
    int num;         /* 拼出来的四位数 */
    int r;           /* 可能的平方根 */

    for (a = 1; a <= 9; a++) {          /* 千位不能是 0 */
        for (b = 0; b <= 9; b++) {
            num = 1100 * a + 11 * b;

            /* 四位数的平方根落在 32 ~ 99 之间
               （31^2=961 不是四位数，100^2=10000 超了） */
            for (r = 32; r <= 99; r++) {
                if (r * r == num) {
                    printf("%d = %d * %d\n", num, r, r);
                }
            }
        }
    }
    return 0;
}