#include <stdio.h>

int main(){
    int a[1000];                     /* 最多存 1000 个数，题目说 n ≤ 1000 */
    int i,j,n;
    scanf("%d",&n);

    for (i = 0; i < n; i++){
        scanf("%d",&a[i]);           /* 普通变量必须加 & 取地址，只有字符数组名不用加 */
    }

    /* ========== 找最长"严格上升"的连续段 ==========
       cur     = 当前这一段有多长
       bestLen = 历史上最长的一段（这个才是答案）
       注意：单独一个数自己就算一段，长度是 1，
       所以两个变量都从 1 开始，不是从 0 */
    int cur = 1,bestLen = 1;

    /* 从 j = 1 开始：因为要拿 a[j] 和 a[j-1] 比较，
       从 0 开始会读到 a[-1]，越界读到的是垃圾值，C 不会拦你 */
    for (j = 1; j < n; j++){
        if (a[j] > a[j - 1]){        /* 严格上升：后一个必须比前一个大，相等不算 */
            cur++;                   /* 还在上升，接着数 */
        } else {
            cur = 1;                 /* 断了：从当前这个数重新开一段，注意是 1 不是 0 */
        }
        if (cur > bestLen) bestLen = cur;   /* 每圈都更新一次最高纪录 */
    }

    /* 标签 maxLen= 必须和题目一字不差；值要打 bestLen（历史最长），不是 cur */
    printf("maxLen=%d\n",bestLen);
    return 0;
}
