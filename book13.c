#include <stdio.h>

/* 第 13 题（教材 108 页）

   亲和数：A 的全部真因子（包括 1，不包括 A 本身）之和等于 B，
   并且 B 的全部真因子之和等于 A，那么 A 和 B 是一对亲和数。
   例：220 的真因子和是 284，284 的真因子和是 220。
   求 3000 以内所有的亲和数对。 */

/* 求 n 的真因子之和：从 1 试到 n-1，能整除就加进去 */
int sumDiv(int n)
{
    int i, s = 0;

    for (i = 1; i < n; i++) {
        if (n % i == 0) {
            s = s + i;
        }
    }
    return s;
}

int main(void)
{
    int a, b;

    for (a = 2; a <= 3000; a++) {
        b = sumDiv(a);              /* 先算出 a 的"搭档" */

        /* 三个条件缺一不可：
           1. b > a            只输出一次，避免 (220,284) 和 (284,220) 重复
           2. b <= 3000        题目要求两个数都在 3000 以内
           3. sumDiv(b) == a   对方的真因子和也要等于自己，才叫"互相" */
        if (b > a && b <= 3000 && sumDiv(b) == a) {
            printf("(%d, %d)\n", a, b);
        }
    }
    return 0;
}